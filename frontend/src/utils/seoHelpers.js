/**
 * Generates an extensive SEO keyword string from a product object.
 * @param {Object} product - The product object from the database
 * @returns {string} - A comma separated list of keywords
 */
export const generateProductKeywords = (product) => {
  if (!product) return '';

  const keywords = new Set();
  
  // Brand & Domain
  keywords.add('রঙবতী');
  keywords.add('Ronggoboti');
  keywords.add('ronggoboti.shop');
  keywords.add('Ronggoboti BD');
  keywords.add('রঙবতী ফ্যাশন');
  keywords.add('রঙবতী ডট শপ');

  // Basic product attributes
  if (product.name) {
    keywords.add(product.name);
    keywords.add(`buy ${product.name} online`);
    keywords.add(`${product.name} price in BD`);
    keywords.add(`${product.name} online shopping Bangladesh`);
    keywords.add(`${product.name} Ronggoboti`);
    keywords.add(`রঙবতী ${product.name}`);
  }
  
  if (product.category) {
    keywords.add(`${product.category} in BD`);
    keywords.add(`premium ${product.category} Bangladesh`);
    keywords.add(`buy ${product.category} online Dhaka`);
    keywords.add(`best ${product.category} in Bangladesh`);
    keywords.add(`designer ${product.category}`);
    keywords.add(`latest ${product.category} collection 2026`);

    // Match category dictionary
    Object.keys(CATEGORY_KEYWORDS_MAP).forEach(catKey => {
      if (new RegExp(catKey.replace(/[-/\\^$*+?.()|[\]{}]/g, '\\$&'), 'i').test(product.category)) {
        CATEGORY_KEYWORDS_MAP[catKey].forEach(k => keywords.add(k));
      }
    });
  }
  
  if (product.brand) {
    keywords.add(`${product.brand} clothing`);
    keywords.add(`${product.brand} ${product.category || ''}`.trim());
  }

  // Delivery & Service Intent
  keywords.add('মেয়েদের পোশাক অনলাইন শপ বাংলাদেশ');
  keywords.add('ক্যাশ অন ডেলিভারি শাড়ি ও জামা');
  keywords.add('cash on delivery womens clothing BD');
  keywords.add('online shopping BD home delivery');
  keywords.add('authentic womens fashion house dhaka');

  // Colors & Sizes
  if (product.colors && Array.isArray(product.colors)) {
    product.colors.forEach(color => {
      keywords.add(`${color} ${product.category || 'womens dress'}`);
      keywords.add(`${color} ${product.name || ''}`.trim());
    });
  }

  if (product.sizes && Array.isArray(product.sizes)) {
    product.sizes.forEach(size => {
      keywords.add(`size ${size} ${product.category || ''}`.trim());
    });
  }

  return Array.from(keywords).filter(Boolean).join(', ');
};

/**
 * Generates SEO metadata for category listing pages.
 */
export const generateCategoryMeta = (categoryName) => {
  const catKeywords = CATEGORY_KEYWORDS_MAP[categoryName] || [];
  const baseTitle = `${categoryName} Collection | রঙবতী (Ronggoboti) Fashion Bangladesh`;
  const baseDesc = `Explore our exclusive ${categoryName} collection at রঙবতী (Ronggoboti.shop). Handcrafted with authentic fabrics, exquisite embroidery, and timeless Bengali elegance. Fast Cash on Delivery across Bangladesh.`;
  const keywordsStr = ['রঙবতী', 'Ronggoboti', categoryName, `${categoryName} price in BD`, ...catKeywords].join(', ');

  return {
    title: baseTitle,
    description: baseDesc,
    keywords: keywordsStr
  };
};

